CREATE TABLE IF NOT EXISTS public.pacientes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    ubicacion text NOT NULL CHECK (
        ubicacion IN (
            'Sala de preparación',
            'Cirugía',
            'Sala de recuperación',
            'Suministrar dieta'
        )
    ),
    fecha_registro timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.usuarios_sistema (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    usuario varchar(40) NOT NULL UNIQUE,
    clave_hash varchar(255) NOT NULL,
    rol varchar(16) NOT NULL DEFAULT 'usuario' CHECK (rol IN ('master', 'usuario')),
    creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.dietas_pacientes (
    paciente_id integer PRIMARY KEY,
    dieta varchar(255) NOT NULL,
    suministrada boolean NOT NULL DEFAULT false,
    fecha_actualizacion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.php_sessions (
    session_id varchar(128) PRIMARY KEY,
    session_data text NOT NULL,
    updated_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS php_sessions_updated_at_idx
    ON public.php_sessions (updated_at);
